def _docx_bytes() -> bytes:
    import io
    import zipfile

    global _docx_cache
    if _docx_cache is not None:
        return _docx_cache
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(
            "[Content_Types].xml",
            '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            '<Default Extension="xml" ContentType="application/xml"/>'
            '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            '<Override PartName="/word/document.xml" '
            'ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>'
            "</Types>",
        )
        archive.writestr(
            "_rels/.rels",
            '<?xml version="1.0"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            '<Relationship Id="rId1" '
            'Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" '
            'Target="word/document.xml"/></Relationships>',
        )
        archive.writestr(
            "word/document.xml",
            '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
            "<w:body><w:p><w:r><w:t>carrier</w:t></w:r></w:p></w:body></w:document>",
        )
    _docx_cache = buffer.getvalue()
    return _docx_cache


def sample(ext: str, directory: str | None = None) -> str:
    """Write a fresh valid carrier for `ext` and return its path."""
    folder = directory or tempfile.mkdtemp(prefix="hackit-carrier-")
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, "carrier." + ext)
    if ext == "svg":
        data = MINIMAL_SVG.encode()
    elif ext == "docx":
        data = _docx_bytes()
    else:
        key = "s." + ("html" if ext == "htm" else ext)
        data = base64.b64decode(SAMPLES[key])
    with open(path, "wb") as handle:
        handle.write(data)
    return path
